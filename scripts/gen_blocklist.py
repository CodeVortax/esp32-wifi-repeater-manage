#!/usr/bin/env python3
"""Builds src/blocklist_data.h, the ad / tracker list that lives in flash.

Input : blocklist/sources/*.txt (one domain per line), blocklist/extra.txt,
        blocklist/keep.txt (names that must never be blocked)
Output: a Golomb-Rice coded set of 64-bit name hashes, about 2.7 bytes per name.

The format is read by src/adblock.cpp (blocklist_contains). A name is stored only as a
hash, so a very rare false match is possible (about 1 in a million per lookup); the
Allow list in the dashboard fixes any that you meet.

    python3 scripts/gen_blocklist.py
"""
import glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MBITS = 20           # false-match rate 2^-20 per lookup
BLOCK = 64           # entries per index block


def fnv1a64(s: str) -> int:
    h = 0xcbf29ce484222325
    for b in s.encode():
        h ^= b
        h = (h * 0x100000001b3) & 0xFFFFFFFFFFFFFFFF
    return h


def read_list(path):
    out = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip().lower()
        if line:
            out.append(line)
    return out


def suffixes(d):
    p = d.split(".")
    return [".".join(p[i:]) for i in range(len(p) - 1)]      # at least two labels


def collect():
    names = set()
    for f in sorted(glob.glob(os.path.join(ROOT, "blocklist/sources/*.txt"))):
        names.update(read_list(f))
    names.update(read_list(os.path.join(ROOT, "blocklist/extra.txt")))
    keep = set(read_list(os.path.join(ROOT, "blocklist/keep.txt")))
    dropped_keep = sorted(n for n in names if any(k == n or k.endswith("." + n) for k in keep))
    names -= set(dropped_keep)
    # a listed parent already covers every child
    before = len(names)
    names = {n for n in names if not any(s in names for s in suffixes(n)[1:])}
    return sorted(names), dropped_keep, before - len(names)


class BitWriter:
    def __init__(self):
        self.bits = []
    def put(self, value, n):
        for i in range(n - 1, -1, -1):
            self.bits.append((value >> i) & 1)
    def tell(self):
        return len(self.bits)
    def bytes(self):
        b = self.bits + [0] * (-len(self.bits) % 8)
        return bytes(sum(b[i + j] << (7 - j) for j in range(8)) for i in range(0, len(b), 8))


def encode(values, k):
    """values: sorted unique ints. Returns (index, stream)."""
    w = BitWriter()
    index = []
    for j in range(0, len(values), BLOCK):
        blk = values[j:j + BLOCK]
        index.append((blk[0], w.tell()))
        for a, b in zip(blk, blk[1:]):
            d = b - a
            q = d >> k
            w.put((1 << q) - 1, q)      # q ones ...
            w.put(0, 1)                 # ... and a zero
            w.put(d & ((1 << k) - 1), k)
    return index, w.bytes()


def build(names):
    n = len(names)
    rng = n << MBITS
    vals = sorted({fnv1a64(x) % rng for x in names})
    best = None
    for k in range(14, 23):
        idx, stream = encode(vals, k)
        if best is None or len(stream) < len(best[2]):
            best = (k, idx, stream)
    k, idx, stream = best
    out = bytearray(b"BL\x01")
    out += bytes([k, MBITS, BLOCK])
    out += len(vals).to_bytes(4, "little") + n.to_bytes(4, "little")
    out += len(idx).to_bytes(2, "little")
    for first, off in idx:
        out += first.to_bytes(5, "little") + off.to_bytes(3, "little")
    out += stream
    return bytes(out), len(vals)


def write_header(path, var, names, comment):
    data, count = build(names)
    lines = ["// GENERATED by scripts/gen_blocklist.py - do not edit.", "// %d names, %d bytes. %s" % (len(names), len(data), comment),
             "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
             "static const size_t %s_BYTES = %d;" % (var, len(data)), "static const uint8_t %s_DATA[] = {" % var]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    open(path, "w").write("\n".join(lines) + "\n")
    print("%s: %d names -> %d bytes" % (var, len(names), len(data)))


def main():
    adult = os.path.join(ROOT, "blocklist/adult/names.txt")
    if os.path.exists(adult):
        write_header(os.path.join(ROOT, "src/adult_data.h"), "ADULTLIST", sorted(set(read_list(adult))),
                     "Chosen by scripts/pick_adult.py from blocklistproject/Lists (Unlicense) and Bon-Appetit/porn-domains (CC BY-SA 4.0).")
    names, dropped_keep, collapsed = collect()
    data, count = build(names)
    lines = [
        "// GENERATED by scripts/gen_blocklist.py - do not edit.",
        "// %d names (%d dropped by keep.txt, %d children folded into listed parents)," % (len(names), len(dropped_keep), collapsed),
        "// %d bytes. Sources: Peter Lowe's list, AdAway (CC BY 3.0), blocklist/extra.txt." % len(data),
        "#pragma once", "#include <stdint.h>", "#include <stddef.h>",
        "static const size_t BLOCKLIST_BYTES = %d;" % len(data),
        "static const uint8_t BLOCKLIST_DATA[] = {",
    ]
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in data[i:i + 24]) + ",")
    lines.append("};")
    path = os.path.join(ROOT, "src/blocklist_data.h")
    open(path, "w").write("\n".join(lines) + "\n")
    open(os.path.join(ROOT, "blocklist/compiled-names.txt"), "w").write("\n".join(names) + "\n")
    print("%d names -> %d bytes (%.2f bytes/name); keep.txt removed %d; folded %d" % (
        len(names), len(data), len(data) / len(names), len(dropped_keep), collapsed))
    print("removed by keep.txt:", ", ".join(dropped_keep[:40]))


if __name__ == "__main__":
    sys.exit(main())
